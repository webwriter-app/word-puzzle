import { customElement, property, state } from 'lit/decorators.js';

import { WebwriterWordPuzzleGrid } from '../components/webwriter-word-puzzle-grid';
import { WordClue, defaultCell } from '../model/crossword-gen';
import { WebwriterWordPuzzleCluebox } from '../components/webwriter-word-puzzle-cluebox';
import { WebwriterWordPuzzleClueboxInput } from '../components/webwriter-word-puzzle-cluebox-input';

import { crossword_styles } from '../components/word-puzzle.styles'
import pencil_square from '@tabler/icons/outline/pencil.svg';
import check_circle from '@tabler/icons/outline/circle-check.svg';

import { type MsgFn } from "@lit/localize";
import { sourceLocale, targetLocales } from "../../localization/generated/locale-codes";


function stopCtrlPropagation(event: KeyboardEvent): void {
    if (event.ctrlKey) {
        event.stopPropagation()
    }
}

/**
 * Data type for the crossword context.
 * 
 * ```typescript
 * {
 *   across: boolean | null,
 *   clue: number | null
 * }
 * ```
 */
export interface CwContext {
    across: boolean | null,
    clue: number | null
}

/**
 * Word puzzles for WebWriter: a crossword generated from a list of words and clues, or a
 * find-the-words puzzle. The widget owns a grid element and a clue panel; the words and clues
 * are entered in a drawer in edit mode, and the crossword layout is generated by
 * `src/model/crossword-gen.ts`. Other puzzle types can be added through the `type` property.
 *
 * Keyboard: in a crossword, type letters; arrow keys move, Space changes direction, Tab and Shift+Tab
 * jump to the next and previous clue, Escape leaves the grid. In find-the-words, arrow keys move between
 * letters and Enter or Space marks the first and then the last letter of a word. Pointer and touch drag a
 * line over the letters of a word. The widget scales its grid with its width (300 to 2100 px) and prints
 * as a paper puzzle: the grid and the clues, without buttons.
 *
 * Conversions: a `dl` (a word in each `dt`, its clue in the `dd`) and a `ul` or `ol` (a word in each `li`) become a
 * puzzle; the words export as `dl`. Files: `.csv` (word and clue columns, header optional, comma, semicolon or tab),
 * `.txt` (one word per line, a tab starts the clue) and `.json` (the widget's own data with the layout) import; the
 * same three export. A file import without layout generates the puzzle, so the words are placed anew. CSV and text
 * keep only words and clues: the layout and the puzzle type are dropped. A word that is already in the list is
 * imported once.
 *
 * Signals: `progress` is the share of the puzzle the reader has solved, from 0 to 1: letters that match the answer
 * in a crossword, words found in find-the-words. `solved` is true when everything is solved. Neither is saved.
 *
 * Styling: the text follows `--ww-text-color` and `--ww-font-family`; the focus and selection tint follows
 * `--ww-theme-accent-1`.
 *
 * @summary Crossword and find-the-words puzzles with a word and clue editor.
 * @part puzzle - The frame around the grid and the clues.
 * @part grid - The element that holds the grid.
 * @part cell - One cell of the grid.
 * @part clues - The element that holds the clue tables.
 */
@customElement("webwriter-word-puzzle")
export class WebwriterWordPuzzle extends LitElementWw {
    static dataType = "application/json";

    static convertFrom = {
        dl: "loadDl",
        ul: "loadList",
        ol: "loadList",
        ".csv": "importCsv",
        ".txt": "importText",
        ".json": "importJson",
    }

    static convertTo = {
        dl: "toDl",
        "text/csv": "exportCsv",
        "text/plain": "exportText",
        "application/json": "exportJson",
    }

    static styles = crossword_styles

    static scopedElements = {
        "sl-button": SlButton,
        "sl-icon": SlIcon,
        "webwriter-word-puzzle-grid": WebwriterWordPuzzleGrid,
        "webwriter-word-puzzle-cluebox": WebwriterWordPuzzleCluebox,
        "webwriter-word-puzzle-cluebox-input": WebwriterWordPuzzleClueboxInput
    }

    static options = {
        type: {
            type: "select" as const,
            group: "puzzle",
            label: (widget: {msg: MsgFn}) => widget.msg("Puzzle Type"),
            options: [
                { value: "crossword", label: (widget: {msg: MsgFn}) => widget.msg("Crossword") },
                { value: "find-the-words", label: (widget: {msg: MsgFn}) => widget.msg("Find the words") },
            ],
        },
    }

    static optionGroups = {
        puzzle: { label: (widget: {msg: MsgFn}) => widget.msg("Puzzle"), collapsible: true, advanced: false },
    }

    static actions = {
        editWords: { label: (widget: {msg: MsgFn}) => widget.msg("Edit words"), group: "puzzle", icon: "Edit", intent: "default" as const },
        checkAnswers: { label: (widget: {msg: MsgFn}) => widget.msg("Check answers"), group: "puzzle", icon: "Check", intent: "default" as const },
        generatePuzzle: { label: (widget: {msg: MsgFn}) => widget.msg("Generate puzzle"), group: "puzzle", confirm: (widget: {msg: MsgFn}) => widget.msg("Place the words on a new grid? The current layout is replaced."), intent: "danger" as const },
        clearAnswers: { label: (widget: {msg: MsgFn}) => widget.msg("Clear answers"), group: "puzzle", confirm: (widget: {msg: MsgFn}) => widget.msg("Clear all letters and found words?"), intent: "danger" as const },
    }

    // drawer: the editor reads the labels again after a language change.
    localize = localizer(this, { sourceLocale, targetLocales, load: (locale) => import(`../../localization/generated/${locale}.ts`), drawer: true });
    readonly msg = this.localize.msg;
    readonly #permissions = new Permissions(this);
    readonly #data = jsonData<{ wordsClues: WordClue[] }>(this, {
        defaults: { wordsClues: [] },
        validate: ({ wordsClues }) => Array.isArray(wordsClues),
        changed: ({ wordsClues }) => this.setWordsCluesChildren(wordsClues),
    });

    readonly #progress = signal(0);

    /** Published for other widgets: `progress` (0 to 1) and `solved`. */
    readonly signals = {
        progress: computed(() => this.#progress.get()),
        solved: computed(() => this.#progress.get() >= 1),
    };

    /**
     * Type of word puzzle
     */
    @property({ type: String, attribute: true, reflect: true })
    accessor type: 'crossword' | 'find-the-words' = 'crossword';

    /**
     * The list of words grouped with their clues, direction, and word number.
     */
    @state()
    accessor _wordsClues: WordClue[] = []

    /**
     * Current crossword context; across and clue number. Not reactive: the grid and the clue box
     * take it through `set-context` and update themselves.
     */
    _cwContext: CwContext = { across: null, clue: null }

    /** The grid element of the puzzle. */
    private gridW: WebwriterWordPuzzleGrid

    /** The input table for words and clues (author only). */
    private clueInpW: WebwriterWordPuzzleClueboxInput

    /** The panel element of the crossword puzzle, containing the words and clues. */
    private clueW: WebwriterWordPuzzleCluebox

    /**
     * @constructor
     * Constructor for the crossword puzzle
     * 
     * Creates the grid, clue box and clue input elements in the widget's registry.
     */
    constructor() {
        super()
        this.gridW = this.createChild<WebwriterWordPuzzleGrid>("webwriter-word-puzzle-grid")
        this.clueW = this.createChild<WebwriterWordPuzzleCluebox>("webwriter-word-puzzle-cluebox")
        this.clueInpW = this.createChild<WebwriterWordPuzzleClueboxInput>("webwriter-word-puzzle-cluebox-input")
        this.gridW.setAttribute("part", "grid")
        this.gridW.setAttribute("exportparts", "cell")
        this.clueW.setAttribute("part", "clues")
        this.gridW.grid = Array.from({ length: 8 }, () => Array(8).fill(defaultCell()))
        this.gridW.newCrosswordGridDOM(document)

        this.setWordsCluesChildren(this._wordsClues, false)

        this.addEventListener("keydown", stopCtrlPropagation )
        this.addEventListener("generateCw", () => this.generateCwHandler())
        this.addEventListener("set-context", (e) => this.setContextHandler(e as CustomEvent<CwContext>))
        this.addEventListener("set-progress", (e) => this.#progress.set((e as CustomEvent<number>).detail))
        this.addEventListener("set-words-clues", (e) => this.setWordsCluesChildren((e as CustomEvent<WordClue[]>).detail, true))
    }

    private createChild<T extends HTMLElement & { parentComponent: WebwriterWordPuzzle }>(tag: string): T {
        const child = document.createElement(tag, { customElementRegistry: this.registry }) as T
        child.parentComponent = this
        return child
    }

    protected updated(changedProperties: PropertyValues): void {
        if (!changedProperties.has("type")) return;
        this.gridW.requestUpdate();
        this.clueW.requestUpdate();
        this.clueInpW.requestUpdate();
    }

    /** Moves focus into the grid, to the first cell that takes keyboard input. */
    focus(options?: FocusOptions) { this.gridW.focusFirstCell(options); }

    editWords() { this.clueInpW.showDrawer(); }
    checkAnswers() { this.gridW.checkAnswers(this.gridW.grid, this.gridW.gridEl); }

    /** Places the words of the list on a new grid again. Does nothing without words. */
    generatePuzzle() {
        const words = this.#data.get().wordsClues;
        if (words.length) this.setWordsCluesChildren(this.gridW.generateCrossword(words.map(({ word, clueText }) => ({ word, clueText }))), true);
    }

    /** Empties the letters the reader entered, or the words the reader found. */
    clearAnswers() { this.gridW.clearAnswers(); }

    protected generateCwHandler() {
        this.setWordsCluesChildren(this.gridW.generateCrossword(this.clueInpW._wordsClues), true);
        this.clueW.requestUpdate()
    }

    /**
     * Takes a parsed word list as the content of the puzzle. Words that come with a layout keep it; for all others
     * the puzzle is generated.
     */
    protected applyPuzzle({ type, wordsClues, placed }: ParsedPuzzle) {
        if (type) this.type = type;
        if (placed) {
            this.setWordsCluesChildren(wordsClues, true);
            this.gridW.newCrosswordGridDOM(document);
        }
        else this.setWordsCluesChildren(this.gridW.generateCrossword(wordsClues), true);
        this.clueW.requestUpdate();
    }

    /** Parses a file when the import runs and returns the function that applies it. */
    async #prepare(file: File, parse: (text: string) => ParsedPuzzle) {
        let parsed: ParsedPuzzle;
        try {
            parsed = parse(await file.text());
        }
        catch (error) {
            if (!(error instanceof WordListError)) throw error;
            switch (error.code) {
                case "empty": throw new Error(this.msg("The file contains no words."));
                case "json": throw new Error(this.msg("The file is not valid JSON."));
                case "shape": throw new Error(this.msg("The file does not describe a word puzzle."));
                case "layout": throw new Error(this.msg("The layout of the puzzle in the file is not valid."));
            }
        }
        return () => this.applyPuzzle(parsed);
    }

    importCsv(file: File) { return this.#prepare(file, parseWordCsv); }
    importText(file: File) { return this.#prepare(file, parseWordText); }
    importJson(file: File) { return this.#prepare(file, parsePuzzleJson); }

    /** The words that are placed or not, the way the data block keeps them. */
    #words(): WordClue[] { return this.#data.get().wordsClues.filter(entry => entry.word); }

    exportCsv() { return new File([wordCsv(this.#words())], "word-puzzle.csv", { type: "text/csv" }); }
    exportText() { return new File([wordText(this.#words())], "word-puzzle.txt", { type: "text/plain" }); }
    exportJson() { return new File([puzzleJson(this.type, this.#words())], "word-puzzle.json", { type: "application/json" }); }

    /** A list of words (a `dt` with an optional `dd`). Declines a source without a word. */
    loadDl(fragment: DocumentFragment) {
        const rows: [string, string][] = [];
        for (const item of fragment.querySelectorAll("dl > dt, dl > dd, dl > div > dt, dl > div > dd")) {
            const text = item.textContent ?? "";
            if (item.localName === "dt") rows.push([text, ""]);
            else if (rows.length) rows[rows.length - 1][1] += ` ${text}`;
        }
        return this.loadRows(rows);
    }

    /** A list of words (one per `li`). */
    loadList(fragment: DocumentFragment) {
        const items = Array.from(fragment.querySelectorAll("ul > li, ol > li"), item => [item.textContent ?? "", ""] as [string, string]);
        return this.loadRows(items);
    }

    private loadRows(rows: [string, string][]) {
        let parsed: ParsedPuzzle;
        try {
            parsed = parseWordRows(rows);
        }
        catch {
            return false;
        }
        this.applyPuzzle(parsed);
        return true;
    }

    /** The words as a `dl`: each word in a `dt`, its clue in a `dd`. Null without words. */
    toDl() {
        const words = this.#words();
        if (!words.length) return null;
        const list = document.createElement("dl");
        for (const { word, clueText } of words) {
            const term = document.createElement("dt");
            term.textContent = word;
            list.append(term);
            if (clueText) {
                const definition = document.createElement("dd");
                definition.textContent = clueText;
                list.append(definition);
            }
        }
        return list;
    }

    protected setContextHandler(e: CustomEvent<CwContext>) {
        this._cwContext = e.detail
        this.gridW._cwContext = e.detail
        this.clueW.highlightContext(e.detail)
    }

    protected setWordsCluesChildren(wordsClues: WordClue[], persist = false) {
        this._wordsClues = wordsClues
        // A block the widget could not read is replaced, as it always was.
        if (persist) this.#data.set({ wordsClues }, { force: this.#data.invalid });
        this.gridW._wordsClues = wordsClues
        this.clueW._wordsClues = wordsClues
        this.clueInpW._wordsClues = wordsClues
        this.clueInpW.reloadUnplacedMarkers(wordsClues);
    }

    render() {
        this.setWordsCluesChildren(this._wordsClues, false)
        return (html`
            <div class="wrapper" part="puzzle">
                <div class="cw-grid-wrapper">
                    ${this.gridW}
                    <div class="button-div">
                        <sl-button id="edit-words" data-ww-can="edit" title="${this.msg("Edit words")}" class="crossword-button" variant="default" @click=${() => this.clueInpW.showDrawer()}>
                            <sl-icon slot="prefix" src=${pencil_square}></sl-icon>
                            <div class="button-content">
                                ${this.msg("Edit words")}
                            </div>
                        </sl-button>
                        ${this.type == "crossword" || this.#permissions.editing ? html`<sl-button id="answer-check" variant="success" title=${this.type == "crossword" ? this.msg("Check answers") : this.msg("Show answers")} class="crossword-button" variant="default" @click=${() => this.gridW.checkAnswers(this.gridW.grid, this.gridW.gridEl)}>
                            <sl-icon slot="prefix" src=${check_circle}></sl-icon>
                            <div class="button-content">
                                ${this.type == "crossword" ? this.msg("Check answers") : this.msg("Show answers")}
                            </div>
                        </sl-button>` : html``}
                    </div>
                </div>

                <div class="cw-cluebox-wrapper">
                    ${this.clueInpW}${this.clueW}
                </div>
            </div>
            `)
    }
}

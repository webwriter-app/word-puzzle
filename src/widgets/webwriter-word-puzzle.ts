import { localizer } from '@webwriter/lit/localize';
import { Permissions } from '@webwriter/lit/permissions';


declare global {interface HTMLElementTagNameMap {
        "webwriter-word-puzzle": WebwriterWordPuzzle;
    }
}

function stopCtrlPropagation(event: KeyboardEvent): void {
    if (event.ctrlKey) {
        event.stopPropagation()
    }
}

/**
 * Data type for the crossword context.
 * 
 * ```typescript
 * {
 *   across: boolean | null,
 *   clue: number | null
 * }
 * ```
 */
export interface CwContext {
    across: boolean | null,
    clue: number | null
}

/**
 * Word puzzles for WebWriter: a crossword generated from a list of words and clues, or a
 * find-the-words puzzle. The widget owns a grid element and a clue panel; the words and clues
 * are entered in a drawer in edit mode, and the crossword layout is generated by
 * `src/model/crossword-gen.ts`. Other puzzle types can be added through the `type` property.
 *
 * @summary Crossword and find-the-words puzzles with a word and clue editor.
 */
@customElement("webwriter-word-puzzle")
export class WebwriterWordPuzzle extends LitElementWw {
    static dataType = "application/json";

    static styles = crossword_styles

    static scopedElements = {
        "sl-button": SlButton,
        "sl-icon": SlIcon,
        "sl-alert": SlAlert,
        "sl-drawer": SlDrawer,
        'sl-select': SlSelect,
        'sl-option': SlOption,
        "webwriter-word-puzzle-grid": WebwriterWordPuzzleGrid,
        "webwriter-word-puzzle-cluebox": WebwriterWordPuzzleCluebox,
        "webwriter-word-puzzle-cluebox-input": WebwriterWordPuzzleClueboxInput
    }

    static options = {
        type: {
            type: "select" as const,
            group: "puzzle",
            label: (widget: {msg: MsgFn}) => widget.msg("Puzzle Type"),
            options: [
                { value: "crossword", label: (widget: {msg: MsgFn}) => widget.msg("Crossword") },
                { value: "find-the-words", label: (widget: {msg: MsgFn}) => widget.msg("Find the words") },
            ],
        },
    }

    static optionGroups = {
        puzzle: { label: (widget: {msg: MsgFn}) => widget.msg("Puzzle"), collapsible: true, advanced: false },
    }

    static actions = {
        editWords: { label: (widget: {msg: MsgFn}) => widget.msg("Edit words"), group: "puzzle", icon: "Edit", intent: "default" as const },
        checkAnswers: { label: (widget: {msg: MsgFn}) => widget.msg("Check answers"), group: "puzzle", icon: "Check", intent: "default" as const },
    }

    // drawer: the editor reads the labels again after a language change.
    localize = localizer(this, { sourceLocale, targetLocales, load: (locale) => import(`../../localization/generated/${locale}.ts`), drawer: true });
    readonly msg = this.localize.msg;
    readonly #permissions = new Permissions(this);
    readonly #data = jsonData<{ wordsClues: WordClue[] }>(this, {
        defaults: { wordsClues: [] },
        validate: ({ wordsClues }) => Array.isArray(wordsClues),
        changed: ({ wordsClues }) => this.setWordsCluesChildren(wordsClues),
    });

    /**
     * Type of word puzzle
     */
    @property({ type: String, attribute: true, reflect: true })
    accessor type: 'crossword' | 'find-the-words' = 'crossword';

    /**
     * The list of words grouped with their clues, direction, and word number.
     */
    @state()
    accessor _wordsClues: WordClue[] = []

    /**
     * Current crossword context; across and clue number
     */
    @state()
    accessor _cwContext: CwContext = { across: null, clue: null }

    /** The grid element of the puzzle. */
    private gridW: WebwriterWordPuzzleGrid

    /** The input table for words and clues (author only). */
    private clueInpW: WebwriterWordPuzzleClueboxInput

    /** The panel element of the crossword puzzle, containing the words and clues. */
    private clueW: WebwriterWordPuzzleCluebox

    /**
     * @constructor
     * Constructor for the crossword puzzle
     * 
     * Creates the grid, clue box and clue input elements in the widget's registry.
     */
    constructor(dimension: number = 8) {
        super()
        this.gridW = this.createChild<WebwriterWordPuzzleGrid>("webwriter-word-puzzle-grid")
        this.clueW = this.createChild<WebwriterWordPuzzleCluebox>("webwriter-word-puzzle-cluebox")
        this.clueInpW = this.createChild<WebwriterWordPuzzleClueboxInput>("webwriter-word-puzzle-cluebox-input")
        this.gridW.grid = Array.from({ length: dimension}, () => Array(dimension).fill(defaultCell()))
        this.gridW.newCrosswordGridDOM(document)

        this.setWordsCluesChildren(this._wordsClues, false)

        this.addEventListener("keydown", stopCtrlPropagation )
        this.addEventListener("generateCw", () => this.generateCwHandler())
        this.addEventListener("set-context", (e) => this.setContextHandler(e as CustomEvent<CwContext>))
        this.addEventListener("set-words-clues", (e) => this.setWordsCluesChildren((e as CustomEvent<WordClue[]>).detail, true))
    }

    private createChild<T extends HTMLElement & { parentComponent: WebwriterWordPuzzle }>(tag: string): T {
        const child = document.createElement(tag, { customElementRegistry: this.registry }) as T
        child.parentComponent = this
        return child
    }

    protected updated(changedProperties: PropertyValues): void {
        if (!changedProperties.has("type")) return;
        this.gridW.requestUpdate();
        this.clueW.requestUpdate();
        this.clueInpW.requestUpdate();
    }

    editWords() { this.clueInpW.showDrawer(); }
    checkAnswers() { this.gridW.checkAnswers(this.gridW.grid, this.gridW.gridEl); }

    protected generateCwHandler() {
        this.setWordsCluesChildren(this.gridW.generateCrossword(this.clueInpW._wordsClues), true);
        this.clueW.requestUpdate()
    }

    protected setContextHandler(e: CustomEvent<CwContext>) {
        this._cwContext = e.detail
        this.gridW._cwContext = this._cwContext
        this.clueW._cwContext = this._cwContext
        this.clueW.highlightContext(this._cwContext)
    }

    protected setWordsCluesChildren(wordsClues: WordClue[], persist = false) {
        this._wordsClues = wordsClues
        // A block the widget could not read is replaced, as it always was.
        if (persist) this.#data.set({ wordsClues }, { force: this.#data.invalid });
        this.gridW._wordsClues = wordsClues
        this.clueW._wordsClues = wordsClues
        this.clueInpW._wordsClues = wordsClues
        this.clueInpW.reloadUnplacedMarkers(wordsClues);
    }

    /**
     * Generates crossword puzzle based off of words in the clue box and 
     * writes it to the DOM.
     * 
     * Based off of Agarwal and Joshi 2020
     */
    protected generateCrossword() {
        // Initialization
        this.gridW.generateCrossword(this._wordsClues)
    }


    render() {
        this.setWordsCluesChildren(this._wordsClues, false)
        return (html`
            <div class="wrapper">
                <div class="cw-grid-wrapper">
                    ${this.gridW}
                    <div class="button-div">
                        <sl-button id="edit-words" data-ww-can="edit" title="${this.msg("Edit words")}" class="crossword-button" variant="default" @click=${() => this.clueInpW.showDrawer()}>
                            <sl-icon slot="prefix" src=${pencil_square}></sl-icon>
                            <div class="button-content">
                                ${this.msg("Edit words")}
                            </div>
                        </sl-button>
                        ${this.type == "crossword" || this.#permissions.editing ? html`<sl-button id="answer-check" variant="success" title=${this.type == "crossword" ? this.msg("Check answers") : this.msg("Show answers")} class="crossword-button" variant="default" @click=${() => this.gridW.checkAnswers(this.gridW.grid, this.gridW.gridEl)}>
                            <sl-icon slot="prefix" src=${check_circle}></sl-icon>
                            <div class="button-content">
                                ${this.type == "crossword" ? this.msg("Check answers") : this.msg("Show answers")}
                            </div>
                        </sl-button>` : html``}
                    </div>
                </div>

                <div class="cw-cluebox-wrapper">
                    ${this.clueInpW}${this.clueW}
                </div>
            </div>
            `)
    }
}
